const dayNumber = (date) => Math.floor(Date.parse(`${date}T00:00:00Z`) / 86400000);
const gcd = (a, b) => (b ? gcd(b, a % b) : a);

/** 그날의 문구 [글, 출처] — 날짜가 같으면 늘 같은 문구, 연이은 날은 서로 멀리 떨어진 문구 */
export function quoteOf(date, list = QUOTES) {
  const n = list.length;
  if (!n) return null;
  let step = Math.round(n * 0.618);
  while (gcd(step, n) !== 1) step++;
  const i = (((dayNumber(date) * step) % n) + n) % n;
  return list[i];
}
