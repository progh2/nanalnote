const gcd = (a, b) => (b ? gcd(b, a % b) : a);

/** 1월 1일 = 0 … 12월 31일 = 365 (윤년 달력 기준이라 2월 29일도 자리가 있다) */
function dayOfYear(date) {
  const [, m, d] = String(date).split('-').map(Number);
  return Math.round((Date.UTC(2000, m - 1, d) - Date.UTC(2000, 0, 1)) / 86400000);
}

/**
 * 그날의 문구 [글, 출처] — 날짜(월·일)마다 정해져 있어 해마다 같은 날 같은 문구가 나오고, 1년에 한 번씩만 나온다.
 * 목록이 출처별로 모여 있으므로 일정 간격으로 건너뛰며 골라 이웃한 날끼리 출처가 섞이게 한다.
 */
export function quoteOf(date, list = QUOTES) {
  const n = list.length;
  if (!n) return null;
  let step = Math.round(n * 0.618);
  while (gcd(step, n) !== 1) step++;
  return list[(dayOfYear(date) * step) % n];
}
